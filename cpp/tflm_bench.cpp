/**
 * tflm_bench.cpp
 * Benchmark the TensorFlow Lite Micro (TFLM) runtime against the same model
 * used by the ColdInfer custom engine.
 *
 * Build (after running scripts/setup_tflm.sh):
 *   g++ -O3 -std=c++17 \
 *       -DINPUT_SIZE=784 \
 *       -DMODEL_HEADER="MNIST_MLP_FP32_tflm_model.h" \
 *       -DMODEL_VAR=MNIST_MLP_FP32_tflm_model \
 *       -I./weights \
 *       -I./third_party/tflm_build/include \
 *       cpp/tflm_bench.cpp \
 *       -L./third_party/tflm_build -ltensorflow-microlite \
 *       -o tflm_bench
 *
 * Output (key:value, one per line — grep-friendly):
 *   TFLM_TIME_US:<n>
 *   TFLM_PEAK_RSS_KB:<n>
 *   TFLM_CPU_USER_US:<n>
 *   TFLM_CPU_SYS_US:<n>
 *   TFLM_ARENA_KB:<n>       ← minimum viable arena (binary-searched)
 */

#include <iostream>
#include <chrono>
#include <fstream>
#include <string>
#include <cstring>
#include <sys/resource.h>

// TFLite Micro headers
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"
#include "tensorflow/lite/micro/system_setup.h"
#include "tensorflow/lite/schema/schema_generated.h"

// Model flatbuffer (generated by python/export_tflite.py)
#ifndef MODEL_HEADER
  #define MODEL_HEADER "MNIST_MLP_FP32_tflm_model.h"
#endif
#include MODEL_HEADER

#ifndef MODEL_VAR
  #define MODEL_VAR MNIST_MLP_FP32_tflm_model
#endif

#ifndef INPUT_SIZE
  #define INPUT_SIZE 784
#endif

// ── Memory arena ─────────────────────────────────────────────────────────────
// Start generous; binary-search for minimum viable size below.
constexpr int kMaxArenaKB = 128;
static uint8_t tensor_arena[kMaxArenaKB * 1024];

// ── Helpers ───────────────────────────────────────────────────────────────────
long get_rss_kb() {
    std::ifstream f("/proc/self/status");
    std::string line;
    while (std::getline(f, line)) {
        if (line.rfind("VmRSS:", 0) == 0) {
            long kb = 0;
            sscanf(line.c_str(), "VmRSS: %ld", &kb);
            return kb;
        }
    }
    struct rusage u; getrusage(RUSAGE_SELF, &u);
    return u.ru_maxrss;
}

// ── Try building an interpreter with a given arena size ──────────────────────
static bool try_arena(int arena_bytes) {
    const tflite::Model* model = tflite::GetModel(MODEL_VAR);
    if (model->version() != TFLITE_SCHEMA_VERSION) return false;

    // Dense-only resolver: FullyConnected + Softmax
    tflite::MicroMutableOpResolver<4> resolver;
    resolver.AddFullyConnected();
    resolver.AddRelu();
    resolver.AddSoftmax();
    resolver.AddDequantize();

    memset(tensor_arena, 0, arena_bytes);
    tflite::MicroInterpreter interp(model, resolver, tensor_arena, arena_bytes);
    return (interp.AllocateTensors() == kTfLiteOk);
}

// ── Find minimum viable arena via binary search ───────────────────────────────
static int find_min_arena_kb() {
    int lo = 1, hi = kMaxArenaKB, best = kMaxArenaKB;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (try_arena(mid * 1024)) { best = mid; hi = mid - 1; }
        else                       { lo = mid + 1; }
    }
    return best;
}

int main() {
    tflite::InitializeTarget();

    const tflite::Model* model = tflite::GetModel(MODEL_VAR);
    tflite::MicroMutableOpResolver<4> resolver;
    resolver.AddFullyConnected();
    resolver.AddRelu();
    resolver.AddSoftmax();
    resolver.AddDequantize();

    // Use generous arena for the actual timing run
    tflite::MicroInterpreter interpreter(
        model, resolver, tensor_arena, kMaxArenaKB * 1024);
    if (interpreter.AllocateTensors() != kTfLiteOk) {
        std::cerr << "AllocateTensors failed\n";
        return 1;
    }

    // Fill input with zeros (same pattern every run — consistent benchmark)
    TfLiteTensor* input = interpreter.input(0);
    memset(input->data.f, 0, INPUT_SIZE * sizeof(float));

    // Warmup
    for (int i = 0; i < 10; ++i) interpreter.Invoke();

    // ── Timed hot loop ───────────────────────────────────────────────────────
    constexpr int kRuns = 1000;
    struct rusage ru_before, ru_after;
    getrusage(RUSAGE_SELF, &ru_before);
    long rss_before = get_rss_kb();

    auto t0 = std::chrono::high_resolution_clock::now();
    for (int i = 0; i < kRuns; ++i) interpreter.Invoke();
    auto t1 = std::chrono::high_resolution_clock::now();

    getrusage(RUSAGE_SELF, &ru_after);
    long rss_after = get_rss_kb();

    long avg_us = std::chrono::duration_cast<std::chrono::microseconds>(t1 - t0).count() / kRuns;
    long cpu_user_us = ((ru_after.ru_utime.tv_sec  - ru_before.ru_utime.tv_sec)  * 1000000L
                      + (ru_after.ru_utime.tv_usec - ru_before.ru_utime.tv_usec)) / kRuns;
    long cpu_sys_us  = ((ru_after.ru_stime.tv_sec  - ru_before.ru_stime.tv_sec)  * 1000000L
                      + (ru_after.ru_stime.tv_usec - ru_before.ru_stime.tv_usec)) / kRuns;

    int min_arena_kb = find_min_arena_kb();

    std::cout << "TFLM_TIME_US:"      << avg_us         << "\n";
    std::cout << "TFLM_PEAK_RSS_KB:"  << rss_after      << "\n";
    std::cout << "TFLM_CPU_USER_US:"  << cpu_user_us    << "\n";
    std::cout << "TFLM_CPU_SYS_US:"   << cpu_sys_us     << "\n";
    std::cout << "TFLM_ARENA_KB:"     << min_arena_kb   << "\n";

    return 0;
}
