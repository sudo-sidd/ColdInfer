"""
Export a trained PyTorch MLP to a TFLite flatbuffer (.tflite) and
convert it to a C array header for inclusion in tflm_bench.cpp.

Usage:
    python python/export_tflite.py --model mnist
    python python/export_tflite.py --model kws

Outputs:
    weights/<MODEL_NAME>_model.tflite
    weights/<MODEL_NAME>_tflm_model.h   ← C array for TFLM binary
"""

import torch
import torch.nn as nn
import numpy as np
import argparse
import os
import struct
import tensorflow as tf

# ── Model definitions (must match train_export.py) ──────────────────────────
class MNIST_MLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc1 = nn.Linear(784, 128)
        self.relu1 = nn.ReLU()
        self.fc2 = nn.Linear(128, 64)
        self.relu2 = nn.ReLU()
        self.fc3 = nn.Linear(64, 10)

    def forward(self, x):
        x = x.view(-1, 784)
        x = self.relu1(self.fc1(x))
        x = self.relu2(self.fc2(x))
        return self.fc3(x)

class KWS_MLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc1 = nn.Linear(1000, 128)
        self.relu1 = nn.ReLU()
        self.fc2 = nn.Linear(128, 64)
        self.relu2 = nn.ReLU()
        self.fc3 = nn.Linear(64, 10)

    def forward(self, x):
        x = x.view(-1, 1000)
        x = self.relu1(self.fc1(x))
        x = self.relu2(self.fc2(x))
        return self.fc3(x)

def pytorch_to_tflite(model, input_shape, output_prefix):
    """Convert a PyTorch model → Keras → TFLite flatbuffer."""
    keras_model = tf.keras.Sequential([
        tf.keras.layers.InputLayer(shape=(input_shape,)),
        tf.keras.layers.Dense(128, activation='relu'),
        tf.keras.layers.Dense(64,  activation='relu'),
        tf.keras.layers.Dense(10),
    ])
    with torch.no_grad():
        keras_model.layers[0].set_weights([
            model.fc1.weight.numpy().T, model.fc1.bias.numpy()])
        keras_model.layers[1].set_weights([
            model.fc2.weight.numpy().T, model.fc2.bias.numpy()])
        keras_model.layers[2].set_weights([
            model.fc3.weight.numpy().T, model.fc3.bias.numpy()])

    converter = tf.lite.TFLiteConverter.from_keras_model(keras_model)
    tflite_bytes = converter.convert()

    # ── Save flatbuffer binary ────────────────────────────────────────────
    tflite_path = f"{output_prefix}_model.tflite"
    with open(tflite_path, 'wb') as f:
        f.write(tflite_bytes)
    print(f"Saved: {tflite_path}  ({len(tflite_bytes):,} bytes)")

    # ── Convert bytes → C array header for TFLM compilation ──────────────
    header_path = f"{output_prefix}_tflm_model.h"
    var_name    = os.path.basename(output_prefix) + "_tflm_model"
    with open(header_path, 'w') as f:
        f.write("#pragma once\n")
        f.write("#include <cstdint>\n\n")
        f.write(f"// Auto-generated by export_tflite.py\n")
        f.write(f"const uint8_t {var_name}[] = {{\n  ")
        hex_vals = [f"0x{b:02x}" for b in tflite_bytes]
        # 12 values per row
        rows = [", ".join(hex_vals[i:i+12]) for i in range(0, len(hex_vals), 12)]
        f.write(",\n  ".join(rows))
        f.write(f"\n}};\n")
        f.write(f"const unsigned int {var_name}_len = {len(tflite_bytes)};\n")
    print(f"Saved: {header_path}")
    return tflite_path, header_path

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", choices=["mnist", "kws"], required=True)
    args = parser.parse_args()

    os.makedirs("weights", exist_ok=True)

    if args.model == "mnist":
        model = MNIST_MLP()
        model.load_state_dict(torch.load("model_weights.MNIST.pt", weights_only=True))
        input_shape   = 784
        output_prefix = "weights/MNIST_MLP_FP32"
    else:
        model = KWS_MLP()
        model.load_state_dict(torch.load("model_weights.KWS.pt", weights_only=True))
        input_shape   = 1000
        output_prefix = "weights/Keyword_Spotting_MLP_FP32"

    model.eval()
    pytorch_to_tflite(model, input_shape, output_prefix)
